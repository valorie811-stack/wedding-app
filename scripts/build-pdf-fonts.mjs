#!/usr/bin/env node
/**
 * Generates lib/pdf/fonts.generated.js — the bundled Noto Sans subset as
 * base64, for @react-pdf to register.
 *
 * Why base64 in a module rather than reading the .ttf files at runtime:
 * the PDF route runs as a serverless function, so anything it touches must be
 * in the function bundle. next.config's `outputFileTracingIncludes` is the
 * documented way to force-include non-imported files, but Turbopack (the
 * default builder in Next 16, and what Vercel runs) silently ignores it —
 * webpack traces the two TTFs, Turbopack traces zero, and neither warns. The
 * fonts were therefore absent in production and fs.readFileSync threw ENOENT.
 *
 * Bytes inside a JS module are bundled by any builder, so this cannot
 * regress the same way. Regenerate after changing the .ttf files:
 *
 *   npm run pdf-fonts:build
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, "..");
const DIR = path.join(ROOT, "lib", "pdf", "fonts");
const OUT = path.join(ROOT, "lib", "pdf", "fonts.generated.js");

const FONTS = [
  ["REGULAR", "NotoSans-Regular.ttf"],
  ["BOLD", "NotoSans-Bold.ttf"],
];

const parts = FONTS.map(([name, file]) => {
  const b64 = fs.readFileSync(path.join(DIR, file)).toString("base64");
  return { name, file, b64 };
});

const body = parts
  .map(({ name, file, b64 }) => `// ${file}\nexport const ${name} =\n  "data:font/ttf;base64,${b64}";`)
  .join("\n\n");

const src = `// Generated by scripts/build-pdf-fonts.mjs — do not edit.
//
// The Noto Sans subset used by the PDF route, inlined as base64 data URLs.
// Inlined rather than read from lib/pdf/fonts/*.ttf at runtime because the
// route is a serverless function: Turbopack ignores outputFileTracingIncludes,
// so the .ttf files are not uploaded with the function and readFileSync fails
// in production. Bytes in a module are bundled by every builder.

${body}
`;

fs.writeFileSync(OUT, src, "utf8");
const kb = Math.round(fs.statSync(OUT).size / 1024);
console.log(`wrote ${path.relative(ROOT, OUT)} (${kb}KB, ${parts.length} fonts)`);
